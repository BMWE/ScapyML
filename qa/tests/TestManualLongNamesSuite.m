classdef TestManualLongNamesSuite < matlab.unittest.TestCase
% Field names built from nested structs must fit MATLAB's 63-character limit
% (namelengthmax), stay unique, and remain usable (Packet set/get, CSV).

    properties
        TempFolder
        HeaderFile
    end

    methods (TestClassSetup)
        function classSetup(testCase)
            import matlab.unittest.fixtures.TemporaryFolderFixture
            testCase.TempFolder = testCase.applyFixture(TemporaryFolderFixture).Folder;
            testCase.HeaderFile = fullfile(testCase.TempFolder, 'long.h');
            fid = fopen(testCase.HeaderFile, 'w');
            fprintf(fid, 'typedef struct { uint8_t very_long_leaf_field_name_number_one; uint8_t very_long_leaf_field_name_number_two; } InnerStructureWithAVeryLongName;\n');
            fprintf(fid, 'typedef struct { InnerStructureWithAVeryLongName first_member_of_the_outer_structure; InnerStructureWithAVeryLongName second_member_of_the_outer_structure; } LongOuter;\n');
            fclose(fid);
        end
    end

    methods (TestMethodSetup)
        function clearRegistry(~)
            ScapyML.ProtocolRegistry.instance().clearAll();
        end
    end

    methods (Access = private)
        function protos = parseQuiet(testCase)
            w = warning('off', 'ScapyML:HeaderParser:NameShortened');
            c = onCleanup(@() warning(w));
            protos = ScapyML.HeaderParser.parseFile(testCase.HeaderFile, 'big');
            reg = ScapyML.ProtocolRegistry.instance();
            for k = 1:numel(protos), reg.register(protos{k}); end
        end
    end

    methods (Test)

        function tcShortenedNamesWarnOnce(testCase)
            testCase.verifyWarning(@() ScapyML.HeaderParser.parseFile(testCase.HeaderFile, 'big'), ...
                'ScapyML:HeaderParser:NameShortened');
        end

        function tcAllNamesFitAndAreUnique(testCase)
            protos = testCase.parseQuiet();
            outer = protos{2};
            names = outer.fieldNames();
            testCase.verifyEqual(numel(names), 4);
            testCase.verifyTrue(all(cellfun(@numel, names) <= namelengthmax), ...
                'every field name must be <= 63 characters');
            testCase.verifyEqual(numel(unique(names)), numel(names), 'names must be unique');
        end

        function tcOriginalNameIsKept(testCase)
            protos = testCase.parseQuiet();
            fds = ScapyML.Packet.collectFields(protos{2}.Fields);
            full = cellfun(@(f) f.FullName, fds, 'UniformOutput', false);
            testCase.verifyTrue(any(strcmp(full, ...
                'first_member_of_the_outer_structure_very_long_leaf_field_name_number_one')));
        end

        function tcPacketSetGetAndBuildWork(testCase)
            testCase.parseQuiet();
            pkt = ScapyML.Packet('LongOuter');
            names = pkt.fieldNames();
            for i = 1:numel(names)
                pkt.set(names{i}, i);
            end
            testCase.verifyEqual(pkt.build(), uint8([1 2 3 4]));
        end

        function tcCsvWithAutoGeneratedLongHeadersLoads(testCase)
            % Headers longer than 63 chars (MATLAB truncates them in
            % readtable) written as the full path, as a tool would generate.
            testCase.parseQuiet();
            f = fullfile(testCase.TempFolder, 'long.csv');
            fid = fopen(f, 'w');
            fprintf(fid, ['first_member_of_the_outer_structure_very_long_leaf_field_name_number_one,', ...
                          'first_member_of_the_outer_structure_very_long_leaf_field_name_number_two,', ...
                          'second_member_of_the_outer_structure_very_long_leaf_field_name_number_one\n']);
            fprintf(fid, '11,12,21\n');
            fclose(fid);
            pkts = ScapyML_fromCSV('LongOuter', f);
            testCase.verifyEqual(numel(pkts), 1);
            bytes = pkts{1}.build();
            testCase.verifyEqual(bytes, uint8([11 12 21 0]));
        end

        function tcCsvHeaderWithProtocolNameAndDotsLoads(testCase)
            testCase.parseQuiet();
            f = fullfile(testCase.TempFolder, 'dots.csv');
            fid = fopen(f, 'w');
            fprintf(fid, ['LongOuter.first_member_of_the_outer_structure.very_long_leaf_field_name_number_two,', ...
                          'LongOuter.second_member_of_the_outer_structure.very_long_leaf_field_name_number_two\n']);
            fprintf(fid, '7,8\n');
            fclose(fid);
            pkts = ScapyML_fromCSV('LongOuter', f);
            testCase.verifyEqual(pkts{1}.build(), uint8([0 7 0 8]));
        end

        function tcCsvHeaderWithOldDoubledMemberNameLoads(testCase)
            % Headers from older versions repeated the member name:
            % outer_pos_pos_x instead of outer_pos_x.
            f = fullfile(testCase.TempFolder, 'dbl.h');
            fid = fopen(f, 'w');
            fprintf(fid, 'typedef struct { uint8_t x; uint8_t y; } Pos3;\n');
            fprintf(fid, 'typedef struct { Pos3 pos; } Mid3;\n');
            fprintf(fid, 'typedef struct { Mid3 m; } Top3;\n');
            fclose(fid);
            protos = ScapyML.HeaderParser.parseFile(f, 'big');
            reg = ScapyML.ProtocolRegistry.instance();
            for k = 1:numel(protos), reg.register(protos{k}); end
            c = fullfile(testCase.TempFolder, 'dbl.csv');
            fid = fopen(c, 'w');
            fprintf(fid, 'm_pos_pos_x,m_pos_pos_y\n5,6\n');
            fclose(fid);
            pkts = ScapyML_fromCSV('Top3', c);
            testCase.verifyEqual(pkts{1}.build(), uint8([5 6]));
        end

        function tcFullNameIsShownButShortNameIsTheKey(testCase)
            testCase.parseQuiet();
            pkt = ScapyML.Packet('LongOuter');
            fullOne = 'first_member_of_the_outer_structure_very_long_leaf_field_name_number_one';
            shortNames = pkt.fieldNames();
            testCase.verifyTrue(all(cellfun(@numel, shortNames) <= namelengthmax));   % data keys are short
            shown = cellfun(@(n) pkt.displayName(n), shortNames, 'UniformOutput', false);
            testCase.verifyTrue(any(strcmp(shown, fullOne)), 'display name must be the full name');
            out = evalc('pkt.show()');
            testCase.verifyTrue(contains(out, fullOne), 'show() must print the full name');
        end

        function tcLuaShowsFullNamesAndOffsetsCarryDisplayName(testCase)
            protos = testCase.parseQuiet();
            out = fullfile(testCase.TempFolder, 'long.lua');
            ScapyML.WiresharkDissector.generate(protos{2}, out);
            testCase.verifyTrue(contains(fileread(out), ...
                'first_member_of_the_outer_structure_very_long_leaf_field_name_number_one'));
            offs = protos{2}.getFieldOffsets();
            testCase.verifyTrue(all(cellfun(@(o) numel(o.name) <= namelengthmax, offs)));
            testCase.verifyTrue(any(cellfun(@(o) strcmp(o.displayName, ...
                'first_member_of_the_outer_structure_very_long_leaf_field_name_number_one'), offs)));
        end

        function tcTwoLevelNestingIsNotDoubled(testCase)
            f = fullfile(testCase.TempFolder, 'two.h');
            fid = fopen(f, 'w');
            fprintf(fid, 'typedef struct { uint8_t x; uint8_t y; } Pos2;\n');
            fprintf(fid, 'typedef struct { Pos2 pos; } Mid;\n');
            fprintf(fid, 'typedef struct { Mid m; } Top;\n');
            fclose(fid);
            protos = ScapyML.HeaderParser.parseFile(f, 'big');
            names = protos{3}.fieldNames();
            testCase.verifyEqual(sort(names(:)'), sort({'m_pos_x', 'm_pos_y'}));
        end

    end
end
